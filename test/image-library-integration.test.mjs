import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createApp} from '../server.mjs';
const png='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=';
test('library HTTP flow preserves originals and chat, persists editable classification and applies only explicitly',async t=>{
  const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'image-library-http-'));
  let modelCalls=0;
  const app=await createApp({dataDir,initialFeeds:[],startProactive:false,startRecall:false,startPursuits:false,startLifeThreads:false,startDossiers:false,startResearch:false,startChatQueue:false,fetchImpl:async()=>{modelCalls++;throw new Error('Image upload must not invoke a model');}});
  const {port}=await app.listen(0),base=`http://127.0.0.1:${port}`;
  t.after(async()=>{await app.close();fs.rmSync(dataDir,{recursive:true,force:true});});
  const request=async(route,body)=>{const response=await fetch(base+route,body===undefined?{}:{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)});return {status:response.status,body:await response.json()};};
  const before=app.store.getMessages('miyue');
  const uploaded=await request('/api/image-library/upload',{image:png,name:'读书原图'});
  assert.equal(uploaded.status,200);assert.equal(uploaded.body.items.length,1);
  const item=uploaded.body.items[0];assert.deepEqual(item.sceneIds,[]);
  assert.equal((await request('/api/scene-images')).body.enabled,false);
  let saved=await request('/api/image-library/metadata',{id:item.id,name:'沙发读书',sceneIds:['study','winter-home'],tags:['坐姿','居家服'],activity:'读书',background:'needs-removal'});
  assert.equal(saved.status,200);assert.equal(saved.body.items[0].activity,'读书');
  const duplicate=await request('/api/image-library/upload',{image:png,name:'另一个文件名'});
  assert.equal(duplicate.body.items.length,1);assert.equal(duplicate.body.items[0].name,'沙发读书');
  assert.equal((await request('/api/image-library/metadata',{id:item.id,sceneIds:['invalid']})).status,400);
  const image=await fetch(base+item.originalUrl);
  assert.equal(image.status,200);assert.equal(image.headers.get('x-content-type-options'),'nosniff');
  assert.deepEqual(Buffer.from(await image.arrayBuffer()),Buffer.from(png.split(',')[1],'base64'));
  assert.equal((await fetch(base+'/api/image-library/files/'+('0'.repeat(64))+'.png')).status,404);
  assert.equal((await fetch(base+'/api/image-library/files/..%2Flife.sqlite')).status,404);
  assert.equal((await request('/api/image-library/apply',{id:item.id,sceneId:'study',variant:'cutout'})).status,400);
  assert.equal((await request('/api/image-library/apply',{id:item.id,sceneId:'study',variant:'original',fit:'contain'})).status,200);
  const scenes=(await request('/api/scene-images')).body;
  assert.equal(scenes.enabled,true);assert.equal(scenes.activeSceneId,'study');
  assert.equal((await request('/api/image-library')).body.items.length,1);
  assert.equal(modelCalls,0);assert.deepEqual(app.store.getMessages('miyue'),before);
  const page=await fetch(base+'/image-library.html');assert.equal(page.status,200);assert.match(await page.text(),/multiple/);
});
